"""Deterministic rendering of views from the model (minimal technical view)."""

import hashlib
import html
import re
from urllib.parse import quote

from . import graph as G
from . import model as M
from . import evidence as E

VIEWS = M.DIR + "/views/"
MARKER = "<!-- Generated by Evermap. Do not edit: run render instead. -->"
MAX_NODES = 30
_INLINE = re.compile(r"([\\`*_\[\]|~#])")


def text(value):
    """Escape model text for inline Markdown: no HTML, links or table breaks."""
    flat = " ".join(str(value).split())
    return _INLINE.sub(r"\\\1", html.escape(flat, quote=False))


def code(value):
    flat = " ".join(str(value).split()).replace("`", "'").replace("|", "\\|")
    return "`%s`" % flat


def label(value):
    """Escape model text for a quoted Mermaid label."""
    flat = " ".join(str(value).split())
    flat = flat.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;").replace(">", "&gt;")
    return flat.replace("#", "&num;").replace("`", "'")


def mark(item):
    return {"inferred": " *(inferred)*", "unknown": " *(unknown)*", "stated": " *(stated)*"}.get(
        item.get("provenance"), "")


def slug(identifier):
    return identifier.split(":", 1)[1]


def flowchart(nodes, edges, styles=None):
    """Mermaid flowchart. nodes: [(id, label)], edges: [(source, target, label)]."""
    names = {ident: "n%d" % i for i, (ident, _) in enumerate(nodes)}
    out = ["```mermaid", "flowchart LR"]
    out += ['  %s["%s"]' % (names[i], label(t)) for i, t in nodes]
    for source, target, title in edges:
        if source in names and target in names:
            arrow = ' -->|"%s"| ' % label(title) if title else " --> "
            out.append("  %s%s%s" % (names[source], arrow, names[target]))
    for style, members in sorted((styles or {}).items()):
        inside = [names[m] for m in sorted(members) if m in names]
        if inside:
            out.append("  class %s %s" % (",".join(inside), style))
    if styles:
        out += ["  classDef added stroke:#2da44e,stroke-width:3px",
                "  classDef removed stroke:#cf222e,stroke-width:3px,stroke-dasharray:4",
                "  classDef modified stroke:#bf8700,stroke-width:3px"]
    return out + ["```"]


def _links(element, depth):
    links, seen = [], set()
    for _, item in E.walk({"evidence": element.get("evidence")}):
        if not E.is_file_evidence(item) or not E.valid_path(item.get("path")):
            continue
        start, end = item["lines"] if E.valid_range(item) else (1, 1)
        name = "%s:%d-%d" % (item["path"], start, end)
        if name not in seen:
            seen.add(name)
            url = "../" * depth + quote(item["path"]) + "#L%d-L%d" % (start, end)
            links.append("[%s](%s)" % (text(name), url))
    return ", ".join(links) or "—"


def _table(header, rows):
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    return out + ["| " + " | ".join(row) + " |" for row in rows]


def _operation_row(op):
    trigger = op.get("trigger") or {}
    auth = op.get("auth") or {}
    tx = ", ".join(code(t["mechanism"]) for t in op.get("transactions") or []) or "—"
    idem = op.get("idempotency") or {}
    where = trigger.get("detail") or trigger.get("channel")
    return [
        "%s<br>%s%s" % (text(op["name"]), code(op["id"]), mark(op)),
        text(trigger.get("type", "")) + (" " + code(where) if where else ""),
        text(op.get("exposure", "")),
        (text(auth["authentication"]) + mark(auth)) if auth.get("authentication") else "not assessed",
        tx if "transactions" in op else "not assessed",
        (text(idem["mechanism"]) + mark(idem)) if idem.get("mechanism") else "not assessed",
        _links(op, 3),
    ]


def _component_page(model, component, graph):
    ident = component["id"]
    out = [MARKER, "", "# %s%s" % (text(component["name"]), mark(component)), "",
           "%s · %s%s" % (code(ident), text(component.get("type", "")),
                          " · " + text(component["technology"]) if component.get("technology") else ""), "",
           text(component["summary"]), ""]
    if component.get("plain"):
        out += ["> " + text(component["plain"]), ""]
    out += ["Evidence: " + _links(component, 3), ""]
    if component.get("responsibilities"):
        out += ["## Responsibilities", ""] + ["- " + text(r) for r in component["responsibilities"]] + [""]
    operations = [o for o in model.of_kind("operation") if o.get("parent") == ident]
    if operations:
        out += ["## Operations", ""]
        out += _table(["Operation", "Trigger", "Exposure", "Authentication", "Transactions", "Idempotency", "Evidence"],
                      [_operation_row(o) for o in operations]) + [""]
    entities = [e for e in model.of_kind("entity") if e.get("parent") == ident]
    if entities:
        out += ["## Data", ""]
        out += _table(["Entity", "Type", "Summary", "Evidence"],
                      [["%s<br>%s%s" % (text(e["name"]), code(e["id"]), mark(e)), text(e.get("type", "")),
                        text(e["summary"]), _links(e, 3)] for e in entities]) + [""]
    rows = []
    for source in [component] + operations:
        for rel in source.get("relations") or []:
            target = model.get(rel["target"])
            rows.append([code(source["id"]), text(rel["type"]),
                         code(rel["target"]) + (" " + text(target["name"]) if target else ""),
                         text(rel.get("condition", "")) or "—", (text(rel.get("provenance", "")) or "as source")])
    if rows:
        out += ["## Relations", ""] + _table(["From", "Relation", "To", "Condition", "Provenance"], rows) + [""]
    if component.get("config"):
        out += ["## Configuration (names only)", ""]
        out += _table(["Name", "Kind", "Purpose"],
                      [[code(c["name"]), text(c.get("kind", "")), text(c.get("purpose", "")) or "—"]
                       for c in component["config"]]) + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def _component_edges(model):
    """Edges between components, declared or implied by operation calls."""
    edges = {}
    for component in model.of_kind("component"):
        for rel in component.get("relations") or []:
            if rel.get("type") == "depends_on":
                edges[(component["id"], rel["target"])] = rel.get("mechanism", "")
    for op in model.of_kind("operation"):
        for rel in op.get("relations") or []:
            if rel.get("type") == "calls":
                target = model.get(rel["target"])
                pair = (op.get("parent"), (target or {}).get("parent"))
                if all(pair) and pair[0] != pair[1]:
                    edges.setdefault(pair, rel.get("mechanism", ""))
    return [(a, b, t) for (a, b), t in sorted(edges.items())]


def _index(model, digest):
    manifest = model.manifest
    system = manifest.get("system") or {}
    coverage = manifest.get("coverage") or {}
    components = model.of_kind("component")
    out = [MARKER, "<!-- evermap:render-hash %s -->" % digest, "",
           "# %s" % text(system.get("name", "System")), ""]
    for name in ("summary", "plain"):
        if system.get(name):
            out += [("> " if name == "plain" else "") + text(system[name]), ""]
    synced = manifest.get("synced") or {}
    if synced.get("commit"):
        out += ["Describes commit %s%s." % (code(synced["commit"]),
                                            " plus uncommitted changes" if synced.get("dirty") else ""), ""]
    out += ["## Contents", ""]
    out += _table(["Kind", "Elements"], [[k, str(len(model.of_kind(k)))] for k in M.KINDS]) + [""]
    if components:
        out += ["## Components", ""]
        out += _table(["Component", "Type", "Summary"],
                      [["[%s](technical/%s.md)%s" % (text(c["name"]), quote(slug(c["id"])), mark(c)),
                        text(c.get("type", "")), text(c["summary"])] for c in components]) + [""]
        shown = components[:MAX_NODES]
        out += ["## Context", ""]
        out += flowchart([(c["id"], c["name"]) for c in shown], _component_edges(model)) + [""]
        if len(components) > MAX_NODES:
            out += ["The diagram shows %d of %d components." % (MAX_NODES, len(components)), ""]
    out += ["## Coverage", "",
            "This model is selective. Something that is not listed here may still exist in the code.", ""]
    for item in coverage.get("unmapped") or []:
        out.append("- Unmapped: %s — %s" % (code(item["path"]), text(item["reason"])))
    for ident in coverage.get("pending") or []:
        out.append("- Not mapped yet: %s" % code(ident))
    for item in coverage.get("limitations") or []:
        out.append("- Limitation: %s" % text(item))
    unknown = [i for i in sorted(model.elements) if model.elements[i].get("provenance") == "unknown"]
    out += ["- Unknown: %s %s" % (code(i), text(model.elements[i]["name"])) for i in unknown]
    return "\n".join(out).rstrip("\n") + "\n"


def digest(model):
    """Hash of everything the views are rendered from, independent of line endings."""
    hasher = hashlib.sha256()
    for path in sorted(model.parsed):
        # Only the manifest and element files: a leftover draft or other stray JSON is not rendered.
        if not path.startswith(M.DIR + "/proposals/") and M.schema_for_path(path) is not None:
            hasher.update(path.encode("utf-8") + b"\0")
            hasher.update(M.dumps(model.parsed[path]).encode("utf-8") + b"\0")
    return "sha256:" + hasher.hexdigest()[:16]


def build(model):
    """{path: text} for all views. Raises KeyError or TypeError on an invalid model."""
    graph = G.Graph(model)
    pages = {VIEWS + "README.md": _index(model, digest(model))}
    for component in model.of_kind("component"):
        pages[VIEWS + "technical/%s.md" % slug(component["id"])] = _component_page(model, component, graph)
    return pages


def existing(model):
    return {p: d for p, d in model.raw.items() if p.startswith(VIEWS)}


def out_of_sync(model):
    try:
        pages = build(model)
    except (KeyError, TypeError, AttributeError, ValueError):
        return [VIEWS + "README.md"]
    current = existing(model)
    stale = [p for p in pages if p not in current or not M.same_text(current[p], pages[p])]
    stale += [p for p in current if p not in pages and MARKER.encode() in current[p][:200]]
    return sorted(stale)


def write(root, model):
    pages = build(model)
    written = [p for p in sorted(pages) if M.write(root, p, pages[p])]
    removed = [p for p, data in sorted(existing(model).items())
               if p not in pages and MARKER.encode() in data[:200]]
    for path in removed:
        M.remove(root, path)
    return {"written": written, "removed": removed, "unchanged": len(pages) - len(written)}
